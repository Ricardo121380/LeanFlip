#!/usr/bin/env node
// Generate package-manager metadata from verified, already-built release assets.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [version, directory, flag] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '') || !directory || (flag && flag !== '--check')) {
  throw new Error('Usage: node scripts/prepare-distribution.mjs VERSION RELEASE_ASSET_DIR [--check]');
}
const renamed = version !== '0.1.0';
const productName = renamed ? 'LeanFlip' : 'CC Switch Lite';
const homepage = 'https://github.com/Ricardo121380/ccswitch-lite';
const sums = new Map((await readFile(join(directory, 'SHA256SUMS'), 'utf8')).trim().split('\n').map(line => {
  const match = /^([a-f0-9]{64})\s+([^/\s]+)$/.exec(line);
  if (!match) throw new Error('Invalid SHA256SUMS line');
  return [match[2], match[1]];
}));
async function asset(name) {
  const sha256 = sums.get(name);
  const actual = createHash('sha256').update(await readFile(join(directory, name))).digest('hex');
  if (!sha256 || actual !== sha256) throw new Error(`Release checksum mismatch: ${name}`);
  return { name, sha256, url: `${homepage}/releases/download/v${version}/${name}` };
}
const cliPrefix = renamed ? 'leanflip' : 'ccsl';
const appPrefix = renamed ? 'leanflip' : 'ccswitch-lite';
const macCli = await asset(`${cliPrefix}_${version}_macos-arm64.tar.gz`);
const linuxCli = await asset(`${cliPrefix}_${version}_linux-x64.tar.gz`);
const macApp = await asset(`${appPrefix}_${version}_macos-arm64.dmg`);
const linuxApp = await asset(`${appPrefix}_${version}_linux-x64.deb`);
const metadata = { version, homepage, platforms: { 'darwin-arm64': { cli: macCli, app: macApp }, 'linux-x64': { cli: linuxCli, app: linuxApp } } };
if (renamed) {
  metadata.appName = 'LeanFlip.app';
  metadata.cliName = 'leanflip';
}
const packagePath = join(root, 'packages/npm/package.json');
const pkg = JSON.parse(await readFile(packagePath, 'utf8'));
pkg.version = version;
pkg.name = renamed ? 'leanflip' : 'ccswitch-lite';
pkg.description = renamed ? 'LeanFlip native CLI, TUI and desktop app installer' : 'CC Switch Lite native CLI and desktop app installer';
pkg.bin = renamed
  ? { leanflip: 'bin/ccsl.js', 'leanflip-app': 'bin/ccsl-app.js' }
  : { ccsl: 'bin/ccsl.js', 'ccsl-app': 'bin/ccsl-app.js' };
const cliCask = renamed ? 'leanflip' : 'ccsl';
const appCask = renamed ? 'leanflip-app' : 'ccswitch-lite';
const files = new Map([
  ['packages/npm/release.json', JSON.stringify(metadata, null, 2) + '\n'],
  ['packages/npm/package.json', JSON.stringify(pkg, null, 2) + '\n'],
  ['packages/npm/LICENSE', await readFile(join(root, 'LICENSE'), 'utf8')],
  ['packages/npm/NOTICE.md', await readFile(join(root, 'NOTICE.md'), 'utf8')],
  [`Casks/${cliCask}.rb`, `# Generated by scripts/prepare-distribution.mjs; installs verified native binaries.
cask "${cliCask}" do
  version "${version}"

  on_macos do
    sha256 "${macCli.sha256}"
    url "${macCli.url}"
    depends_on arch: :arm64
  end

  on_linux do
    sha256 "${linuxCli.sha256}"
    url "${linuxCli.url}"
    depends_on arch: :x86_64
  end

  name "${productName} CLI"
  desc "Manage AI coding-tool providers from a searchable terminal menu"
  homepage "${homepage}"

  binary "${cliCask}"
end
`],
  [`Casks/${appCask}.rb`, `# Generated by scripts/prepare-distribution.mjs; uses the verified macOS release.
cask "${appCask}" do
  version "${version}"
  sha256 "${macApp.sha256}"

  url "${macApp.url}"
  name "${productName}"
  desc "Manage AI coding-tool provider configurations"
  homepage "${homepage}"

  depends_on arch: :arm64
  depends_on :macos

  app "${productName}.app"

  uninstall quit: "dev.ccswitch.lite"
end
`],
]);
for (const [relative, content] of files) {
  const target = join(root, relative);
  if (flag === '--check') {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Stale generated file: ${relative}`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(`${flag === '--check' ? 'Verified' : 'Generated'} Homebrew and npm metadata for v${version}`);
