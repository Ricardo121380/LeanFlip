#!/usr/bin/env node
// Generate package-manager metadata from verified, already-built release assets.
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [version, directory, flag] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '') || !directory || (flag && flag !== '--check')) {
  throw new Error('Usage: node scripts/prepare-distribution.mjs VERSION RELEASE_ASSET_DIR [--check]');
}
// v0.1.0 shipped under an earlier name; it is never regenerated with LeanFlip names.
if (version === '0.1.0') throw new Error('v0.1.0 was published under an earlier name and cannot be regenerated');
// The app's binary name and identifier come from the Tauri config, so the installers always match the build.
const tauri = JSON.parse(await readFile(join(root, 'crates/app/tauri.conf.json'), 'utf8'));
const productName = tauri.productName;
const appBinary = tauri.mainBinaryName;
const bundleId = tauri.identifier;
const cliName = 'leanflip';
const appCask = `${cliName}-app`;
const homepage = 'https://github.com/Ricardo121380/LeanFlip';
const sums = new Map((await readFile(join(directory, 'SHA256SUMS'), 'utf8')).trim().split('\n').map(line => {
  const match = /^([a-f0-9]{64})\s+([^/\s]+)$/.exec(line);
  if (!match) throw new Error('Invalid SHA256SUMS line');
  return [match[2], match[1]];
}));
async function asset(name) {
  const sha256 = sums.get(name);
  const actual = createHash('sha256').update(await readFile(join(directory, name))).digest('hex');
  if (!sha256 || actual !== sha256) throw new Error(`Release checksum mismatch: ${name}`);
  return { name, sha256, url: `${homepage}/releases/download/v${version}/${name}` };
}
const macCli = await asset(`${cliName}_${version}_macos-arm64.tar.gz`);
const linuxCli = await asset(`${cliName}_${version}_linux-x64.tar.gz`);
const macApp = await asset(`${cliName}_${version}_macos-arm64.dmg`);
const linuxApp = await asset(`${cliName}_${version}_linux-x64.deb`);
const metadata = {
  version, homepage, appName: `${productName}.app`, cliName, appBinary, appCask, bundleId,
  platforms: { 'darwin-arm64': { cli: macCli, app: macApp }, 'linux-x64': { cli: linuxCli, app: linuxApp } },
};
const packagePath = join(root, 'packages/npm/package.json');
const pkg = JSON.parse(await readFile(packagePath, 'utf8'));
pkg.version = version;
pkg.name = cliName;
pkg.description = `${productName} native CLI, TUI and desktop app installer`;
pkg.bin = { [cliName]: `bin/${cliName}.js`, [appCask]: `bin/${appCask}.js` };
pkg.files = pkg.files.filter(name => name !== 'NOTICE.md');
const files = new Map([
  ['packages/npm/release.json', JSON.stringify(metadata, null, 2) + '\n'],
  ['packages/npm/package.json', JSON.stringify(pkg, null, 2) + '\n'],
  ['packages/npm/LICENSE', await readFile(join(root, 'LICENSE'), 'utf8')],
  [`Casks/${cliName}.rb`, `# Generated by scripts/prepare-distribution.mjs; installs verified native binaries.
cask "${cliName}" do
  version "${version}"

  on_macos do
    sha256 "${macCli.sha256}"
    url "${macCli.url}"
    depends_on arch: :arm64
  end

  on_linux do
    sha256 "${linuxCli.sha256}"
    url "${linuxCli.url}"
    depends_on arch: :x86_64
  end

  name "${productName} CLI"
  desc "Manage AI coding-tool providers from a searchable terminal menu"
  homepage "${homepage}"

  binary "${cliName}"
end
`],
  [`Casks/${appCask}.rb`, `# Generated by scripts/prepare-distribution.mjs; uses the verified macOS release.
cask "${appCask}" do
  version "${version}"
  sha256 "${macApp.sha256}"

  url "${macApp.url}"
  name "${productName}"
  desc "Manage AI coding-tool provider configurations"
  homepage "${homepage}"

  depends_on arch: :arm64
  depends_on :macos

  app "${productName}.app"

  uninstall quit: "${bundleId}"
end
`],
]);
// Casks and notices from earlier releases are not part of a new release.
const stale = [join(root, 'packages/npm/NOTICE.md')];
const caskDir = join(root, 'Casks');
for (const name of await readdir(caskDir).catch(error => { if (error.code === 'ENOENT') return []; throw error; })) {
  if (!files.has(`Casks/${name}`)) stale.push(join(caskDir, name));
}
for (const path of stale) {
  const present = await readFile(path).then(() => true, error => { if (error.code === 'ENOENT') return false; throw error; });
  if (!present) continue;
  if (flag === '--check') throw new Error(`Stale file from an earlier release: ${path.slice(root.length + 1)}`);
  await rm(path);
}
for (const [relative, content] of files) {
  const target = join(root, relative);
  if (flag === '--check') {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Stale generated file: ${relative}`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(`${flag === '--check' ? 'Verified' : 'Generated'} Homebrew and npm metadata for v${version}`);
